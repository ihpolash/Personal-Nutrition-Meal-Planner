export function searchFood(query) {
  if (!query || query.length < 2) return [];
  const q = query.toLowerCase();
  const words = q.split(/\s+/);
  const scored = FOOD_DB.map(food => {
    const name = food.name.toLowerCase();
    let score = 0;
    for (const word of words) {
      if (name === word) score += 100;
      else if (name.startsWith(word)) score += 50;
      else if (name.includes(word)) score += 20;
      else score -= 5;
    }
    const exactRatio = words.filter(w => name.includes(w)).length / words.length;
    score += exactRatio * 30;
    return { ...food, score };
  });
  return scored.filter(f => f.score > 0).sort((a, b) => b.score - a.score).slice(0, 6);
}
